"""One entrypoint for every agent hook: `t0 hook <name>` reads the tool's event JSON on stdin,
normalizes it (Claude snake_case, Copilot camelCase with JSON-string toolArgs, Kiro), runs the hook,
and writes the tool-specific reply. Exit 2 + stderr = block (portable across the three).
Registrations are generated by gen.py from HOOKS.

Agent hooks are accelerators. The same rules are enforced where they cannot be skipped
(kb check LANE.derived-untouched in KB CI, server rulesets for force-push).
Guards do path/argv checks only (no fold) to stay fast.
"""
from __future__ import annotations

import json
import os
import shlex
import sys
from dataclasses import dataclass
from enum import Enum
from pathlib import Path
from typing import Any, Callable, Mapping

import yaml


class Event(Enum):
    SESSION_START = "session-start"
    SUBAGENT_START = "subagent-start"
    PROMPT_SUBMIT = "prompt-submit"
    PRE_TOOL = "pre-tool"
    STOP = "stop"


@dataclass(frozen=True)
class HookSpec:
    event: Event
    claude: tuple[str, str] | None      # (event name, matcher)
    copilot: str | None                 # event name (Copilot hooks have no matcher)
    kiro: tuple[str, str] | None        # (event name, matcher)  -- Kiro schema inferred, verify


CLAUDE_TOOL_MATCHER = "Bash|Edit|Write|MultiEdit|NotebookEdit|Read|Grep|Glob|mcp__.*"
_PR_TOOL_SUFFIXES = ("create_pull_request", "merge_pull_request", "update_pull_request")

HOOKS: tuple[HookSpec, ...] = (
    HookSpec(Event.SESSION_START, ("SessionStart", "startup|resume|clear|compact"), "sessionStart", ("sessionStart", "")),
    HookSpec(Event.SUBAGENT_START, ("SubagentStart", ""), None, None),
    HookSpec(Event.PROMPT_SUBMIT, ("UserPromptSubmit", ""), "userPromptSubmitted", ("promptSubmit", "")),
    HookSpec(Event.PRE_TOOL, ("PreToolUse", CLAUDE_TOOL_MATCHER), "preToolUse", ("preToolUse", "*")),
    HookSpec(Event.STOP, ("Stop", ""), "agentStop", ("agentStop", "")),
)

_ALIASES = {"pre-tool-edit": Event.PRE_TOOL, "pre-tool-shell": Event.PRE_TOOL, "pre-tool-read": Event.PRE_TOOL}

_SHELL_TOOLS = {"bash", "shell", "execute_bash", "run_in_terminal", "runterminalcommand", "terminal"}
_EDIT_TOOLS = {"edit", "write", "multiedit", "notebookedit", "create", "str_replace_editor", "str_replace",
               "fs_write", "editfiles", "createfile", "replace_string_in_file", "insert_edit_into_file"}
_READ_TOOLS = {"read", "grep", "glob", "ls", "view", "fs_read", "readfile", "read_file", "search", "file_search"}

DERIVED_FILES = frozenset({"index.md", "log.md", "changeset.md"})
ROOT_DERIVED_FILES = frozenset({"profile.md"})


@dataclass(frozen=True)
class HookEvent:
    tool: str                           # claude | copilot | kiro
    event: Event
    cwd: Path
    tool_name: str | None
    tool_input: Mapping[str, Any]
    prompt: str | None


@dataclass(frozen=True)
class HookReply:
    block: bool
    message: str
    inject: bool

    @staticmethod
    def ok() -> "HookReply": return HookReply(False, "", False)
    @staticmethod
    def say(msg: str) -> "HookReply": return HookReply(False, msg, False)
    @staticmethod
    def inject_(text: str) -> "HookReply": return HookReply(False, text, True)
    @staticmethod
    def deny(reason_pt: str) -> "HookReply": return HookReply(True, reason_pt, False)


@dataclass(frozen=True)
class GitVerdict:
    allowed: bool
    reason_pt: str


# ------------------------------------------------------------------ git guard

_GIT_OPTS_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace", "--super-prefix", "--config-env"}
_FORCE_LONG = ("--force", "--force-with-lease", "--force-if-includes")
_PUSH_OPTS_WITH_VALUE = {"-o", "--push-option", "--repo", "--receive-pack", "--exec"}


def _git_subcommand(argv: list[str]) -> tuple[str | None, list[str]]:
    i = 1
    while i < len(argv):
        a = argv[i]
        if a in _GIT_OPTS_WITH_VALUE:
            i += 2
        elif a.startswith("-"):
            i += 1
        else:
            return a, argv[i + 1:]
    return None, []


def check_git(argv: list[str]) -> GitVerdict:
    """Blocks push --force/-f/--force-with-lease/--force-if-includes/+refspec and reset --hard.
    Skips global options (`-C dir`, `-c k=v`, `--git-dir=...`) so `git -C dir push -f` is caught."""
    sub, args = _git_subcommand(argv)
    if sub == "push":
        skip = False
        for a in args:
            if skip:
                skip = False
                continue
            if a in _PUSH_OPTS_WITH_VALUE:
                skip = True
            elif a == "--":
                continue
            elif any(a == f or a.startswith(f + "=") for f in _FORCE_LONG):
                return GitVerdict(False, f"force-push bloqueado (`{a}`): abra um PR ou peça ajuda a um humano")
            elif a.startswith("-") and not a.startswith("--") and "f" in a[1:]:
                return GitVerdict(False, f"force-push bloqueado (`{a}`): abra um PR ou peça ajuda a um humano")
            elif a.startswith("+"):
                return GitVerdict(False, f"force-push bloqueado (refspec `{a}`): abra um PR")
    if sub == "reset" and "--hard" in args:
        return GitVerdict(False, "`git reset --hard` bloqueado: perde trabalho; use `git stash` ou peça a um humano")
    return GitVerdict(True, "")


# ------------------------------------------------------------------ PR guard (gh CLI and GitHub MCP)

_DRAFT_ONLY = "todo PR nasce e fica em draft; marcar pronto, aprovar e fazer merge são do humano ou do CI"


def check_gh(argv: list[str]) -> GitVerdict:
    """Blocks `gh pr ready` (but not `--undo`), `gh pr merge`, `gh pr review --approve|-a`
    and `gh pr create` without `--draft|-d`."""
    if len(argv) < 3 or argv[1] != "pr":
        return GitVerdict(True, "")
    sub, args = argv[2], argv[3:]
    if sub == "ready" and "--undo" not in args:
        return GitVerdict(False, f"`gh pr ready` bloqueado: {_DRAFT_ONLY}")
    if sub == "merge":
        return GitVerdict(False, f"`gh pr merge` bloqueado: {_DRAFT_ONLY}")
    if sub == "review" and any(a in ("--approve", "-a") or a.startswith("--approve=") for a in args):
        return GitVerdict(False, f"`gh pr review --approve` bloqueado: {_DRAFT_ONLY}")
    if sub == "create" and not any(a in ("--draft", "-d", "--draft=true") for a in args):
        return GitVerdict(False, f"`gh pr create` sem `--draft` bloqueado: {_DRAFT_ONLY}; rode de novo com `--draft`")
    return GitVerdict(True, "")


def _is_true(v: Any) -> bool:
    return v is True or (isinstance(v, str) and v.lower() == "true")


def _is_false(v: Any) -> bool:
    return v is False or (isinstance(v, str) and v.lower() == "false")


def check_pr_tool(tool_name: str, ti: Mapping[str, Any]) -> HookReply:
    """GitHub MCP tools, matched by name suffix so every server prefix (`mcp__github__`,
    `github-mcp-server-`, `@github/`) is covered."""
    n = tool_name.lower()
    if n.endswith("create_pull_request") and not _is_true(ti.get("draft")):
        return HookReply.deny(f"`{tool_name}` sem `draft: true` bloqueado: {_DRAFT_ONLY}")
    if n.endswith("merge_pull_request"):
        return HookReply.deny(f"`{tool_name}` bloqueado: {_DRAFT_ONLY}")
    if n.endswith("update_pull_request") and _is_false(ti.get("draft")):
        return HookReply.deny(f"`{tool_name}` com `draft: false` bloqueado: {_DRAFT_ONLY}")
    return HookReply.ok()


# ------------------------------------------------------------------ shell guard

_WRAPPERS = {"sudo", "command", "exec", "nohup", "time", "env"}
_SHELLS = {"bash", "sh", "zsh", "dash"}
_SEPARATORS = {"&&", "||", ";", "|", "&", "(", ")", ";;", "|&"}


def _segments(command: str) -> list[list[str]]:
    lex = shlex.shlex(command.replace("\n", " ; "), posix=True, punctuation_chars=";&|()")
    lex.whitespace_split = True
    try:
        tokens = list(lex)
    except ValueError:
        tokens = command.split()
    segs: list[list[str]] = [[]]
    for t in tokens:
        if t in _SEPARATORS:
            segs.append([])
        else:
            segs[-1].append(t)
    return [s for s in segs if s]


def _strip_prefix(argv: list[str]) -> list[str]:
    i = 0
    while i < len(argv):
        a = argv[i]
        if "=" in a and not a.startswith("-") and a.split("=", 1)[0].replace("_", "").isalnum():
            i += 1
        elif Path(a).name in _WRAPPERS:
            i += 1
            while i < len(argv) and argv[i].startswith("-"):
                i += 1
        else:
            break
    return argv[i:]


def _inbox() -> Path:
    return Path(os.path.expanduser("~")) / ".t0" / "inbox"


def _mentions_inbox(token: str, cwd: Path) -> bool:
    expanded = os.path.expandvars(os.path.expanduser(token))
    if ".t0/inbox" not in expanded:
        return False
    return _under(Path(expanded) if os.path.isabs(expanded) else cwd / expanded, _inbox()) or "~/.t0/inbox" in token


def check_shell(command: str, cwd: Path) -> HookReply:
    for seg in _segments(command):
        argv = _strip_prefix(seg)
        if not argv:
            continue
        prog = Path(argv[0]).name
        if prog in _SHELLS and "-c" in argv[1:-1]:
            inner = check_shell(argv[argv.index("-c") + 1], cwd)
            if inner.block:
                return inner
            continue
        if prog == "git":
            v = check_git(argv)
            if not v.allowed:
                return HookReply.deny(v.reason_pt)
        if prog == "gh":
            v = check_gh(argv)
            if not v.allowed:
                return HookReply.deny(v.reason_pt)
        if prog != "t0" and any(_mentions_inbox(t, cwd) for t in argv):
            return HookReply.deny(_INBOX_REASON)
    return HookReply.ok()


_INBOX_REASON = ("leitura de ~/.t0/inbox bloqueada: transcrição bruta não passa por agente; "
                 "rode `t0 transcript redact <arquivo>` e leia a saída redigida")


# ------------------------------------------------------------------ read guard


def _under(path: Path, root: Path) -> bool:
    try:
        path.resolve().relative_to(root.resolve())
        return True
    except ValueError:
        return False


def check_read(paths: tuple[Path, ...]) -> HookReply:
    if any(_under(p, _inbox()) for p in paths):
        return HookReply.deny(_INBOX_REASON)
    return HookReply.ok()


# ------------------------------------------------------------------ edit guard


def _kb_root(path: Path) -> Path | None:
    """Nearest ancestor whose index.md declares okf_version (the OKF bundle root)."""
    for d in path.parents:
        idx = d / "index.md"
        if idx.is_file():
            try:
                head = idx.read_text(encoding="utf-8")[:2000]
            except OSError:
                continue
            if "okf_version" in head:
                return d
    return None


def _frontmatter(text: str) -> dict[str, Any] | None:
    if not text.startswith("---"):
        return {}
    lines = text.splitlines()
    try:
        end = next(i for i, l in enumerate(lines[1:], 1) if l.strip() == "---")
        data = yaml.safe_load("\n".join(lines[1:end]))
    except (StopIteration, yaml.YAMLError):
        return None
    return data if isinstance(data, dict) else {}


def derived_keys(type_name: str | None) -> frozenset[str]:
    from .profile.table import REGISTRY

    spec = REGISTRY.type_named(type_name) if type_name else None
    return REGISTRY.derived_keys(spec) if spec else frozenset()


Transform = Callable[[str], str | None]   # old text -> new text (None = unknown)


def check_edit(path: Path, transform: Transform | None) -> HookReply:
    """Deny: derived files in a KB (index.md, log.md, changeset.md, root profile.md), edits of existing
    steps/* or gates/* files, and changes to derived frontmatter keys of the file's type."""
    kb = _kb_root(path)
    if kb is None:
        return HookReply.ok()
    rel = path.resolve().relative_to(kb.resolve())
    if rel.name in DERIVED_FILES or (len(rel.parts) == 1 and rel.name in ROOT_DERIVED_FILES):
        return HookReply.deny(f"`{rel}` é derivado e só o kb-render escreve; mude a fonte e rode `t0 kb propose`")
    exists = path.is_file()
    if exists and ("steps" in rel.parts[:-1] or "gates" in rel.parts[:-1]):
        return HookReply.deny(f"`{rel}` é registro imutável; registre um novo com `t0 log`")
    if transform is None:
        return HookReply.ok()
    old = path.read_text(encoding="utf-8") if exists else ""
    new = transform(old)
    if new is None:
        return HookReply.ok()
    before, after = _frontmatter(old), _frontmatter(new)
    if before is None or after is None:
        return HookReply.ok()
    keys = derived_keys(after.get("type") or before.get("type"))
    changed = sorted(k for k in keys if before.get(k) != after.get(k))
    if changed:
        return HookReply.deny(f"chaves derivadas não se editam à mão ({', '.join(changed)}) em `{rel}`; "
                              "estado muda por gate (`t0 gate`), o resto o kb-render deriva")
    return HookReply.ok()


def _transform(ti: Mapping[str, Any]) -> Transform | None:
    replace_keys = ("edits", "old_string", "old_str", "oldString")
    content = next((ti[k] for k in ("content", "file_text", "text") if isinstance(ti.get(k), str)), None)
    if content is not None and not any(k in ti for k in replace_keys):
        return lambda _old: content
    edits = ti.get("edits")
    if isinstance(edits, list):
        pairs = [(e.get("old_string", e.get("oldString")), e.get("new_string", e.get("newString"))) for e in edits]
    else:
        pairs = [(ti.get("old_string", ti.get("old_str", ti.get("oldString"))),
                  ti.get("new_string", ti.get("new_str", ti.get("newString"))))]
    if not all(isinstance(o, str) and isinstance(n, str) for o, n in pairs):
        return None
    every = bool(ti.get("replace_all"))

    def apply(old: str) -> str | None:
        for o, n in pairs:
            if o not in old:
                return None
            old = old.replace(o, n) if every else old.replace(o, n, 1)
        return old
    return apply


# ------------------------------------------------------------------ normalization


def _path_args(ti: Mapping[str, Any]) -> list[str]:
    out = [ti[k] for k in ("file_path", "path", "filePath", "notebook_path", "dir_path") if isinstance(ti.get(k), str)]
    out += [p for p in ti.get("paths", []) or [] if isinstance(p, str)]
    return out


def parse_event(event: Event, raw: Mapping[str, Any], tool: str | None) -> HookEvent:
    if tool is None:
        tool = "copilot" if "toolName" in raw or "toolArgs" in raw else "claude"
    tool_name = raw.get("tool_name") or raw.get("toolName")
    ti: Any = raw.get("tool_input", raw.get("toolArgs", {}))
    if isinstance(ti, str):
        try:
            ti = json.loads(ti)
        except json.JSONDecodeError:
            ti = {"command": ti}
    if not isinstance(ti, dict):
        ti = {}
    prompt = raw.get("prompt") or raw.get("user_prompt") or raw.get("userPrompt")
    return HookEvent(tool, event, Path(raw.get("cwd") or os.getcwd()), tool_name, ti, prompt)


def _classify(tool_name: str | None) -> str:
    n = (tool_name or "").lower()
    if n in _SHELL_TOOLS:
        return "shell"
    if n in _EDIT_TOOLS:
        return "edit"
    if n in _READ_TOOLS:
        return "read"
    return "other"


def pre_tool(ev: HookEvent) -> HookReply:
    kind = _classify(ev.tool_name)
    paths = tuple((ev.cwd / p) if not os.path.isabs(os.path.expanduser(p)) else Path(os.path.expanduser(p))
                  for p in _path_args(ev.tool_input))
    if kind == "shell":
        return check_shell(str(ev.tool_input.get("command", "")), ev.cwd)
    if kind == "read":
        return check_read(paths or (ev.cwd,))
    if kind == "edit":
        for p in paths:
            r = check_edit(p, _transform(ev.tool_input))
            if r.block:
                return r
        return HookReply.ok()
    if ev.tool_name and ev.tool_name.lower().endswith(_PR_TOOL_SUFFIXES):
        return check_pr_tool(ev.tool_name, ev.tool_input)
    return check_read(paths)


# ------------------------------------------------------------------ context hooks


def _context_text(cwd: Path, fmt_name: str) -> str:
    from .context import CardFormat
    from .kb import KB, KBUnavailable

    try:
        card = KB.open().context(None, CardFormat(fmt_name))
    except KBUnavailable as e:
        return str(e)
    except Exception as e:  # the session must start even when the KB layer fails
        return f"t0: contexto do KB indisponível ({type(e).__name__}); siga o AGENTS.md e rode `t0 doctor`."
    return card.text if card else "t0: card em dia."


def session_start(ev: HookEvent) -> HookReply:
    from . import ws

    lines = [_context_text(ev.cwd, "delta")]
    warn = ws.divergence(ev.cwd)
    if warn:
        lines.insert(0, warn)
    text = "\n".join(lines)
    w = ws.locate(ev.cwd)
    if w is not None:
        ws.write_if_changed(w.root / ".t0/context.md", text + "\n")
    return HookReply.inject_(text)


def prompt_submit(ev: HookEvent) -> HookReply:
    from . import ws

    marker = ws.read_bet_marker(ev.cwd)
    if not ev.prompt or marker is None:
        return HookReply.ok()
    data = marker[1]
    own = {data.get("jira"), data.get("active_story"), *(data.get("stories") or [])} - {None}
    projects = {k.split("-")[0] for k in own}
    foreign = sorted({m.group(0) for m in ws.JIRA_KEY_RE.finditer(ev.prompt)
                      if m.group(1) in projects and m.group(0) not in own})
    if not foreign:
        return HookReply.ok()
    return HookReply.say(f"t0: {', '.join(foreign)} não é da bet ativa {data.get('bet')}; "
                         f"se mudou de bet rode `t0 bet use {foreign[0]}`")


def stop(ev: HookEvent) -> HookReply:
    try:
        from .kb import KB

        KB.open().push(if_due=True)
    except Exception:
        pass
    return HookReply.ok()


_HANDLERS: dict[Event, Callable[[HookEvent], HookReply]] = {
    Event.SESSION_START: session_start,
    Event.SUBAGENT_START: lambda ev: HookReply.inject_(_context_text(ev.cwd, "subagent")),
    Event.PROMPT_SUBMIT: prompt_submit,
    Event.PRE_TOOL: pre_tool,
    Event.STOP: stop,
}

_CLAUDE_EVENT = {Event.SESSION_START: "SessionStart", Event.SUBAGENT_START: "SubagentStart",
                 Event.PROMPT_SUBMIT: "UserPromptSubmit"}


def format_reply(ev: HookEvent, reply: HookReply) -> tuple[int, str, str]:
    if reply.block:
        return 2, "", reply.message + "\n"
    if not reply.message:
        return 0, "", ""
    if ev.tool == "claude" and ev.event in _CLAUDE_EVENT:
        out: dict[str, Any] = {"hookSpecificOutput": {"hookEventName": _CLAUDE_EVENT[ev.event],
                                                      "additionalContext": reply.message}}
        if not reply.inject:
            out["systemMessage"] = reply.message
        return 0, json.dumps(out, ensure_ascii=False) + "\n", ""
    return 0, reply.message + "\n", ""


def run_hook(name: str, stdin: bytes, *, tool: str | None = None) -> tuple[int, str, str]:
    """Returns (exit_code, stdout, stderr) formatted for the calling tool. `tool` overrides detection
    (gen passes --tool copilot|kiro in their registrations)."""
    event = _ALIASES.get(name) or next((e for e in Event if e.value == name), None)
    if event is None:
        return 1, "", f"hook desconhecido: {name}\n"
    try:
        raw = json.loads(stdin.decode("utf-8") or "{}")
    except (json.JSONDecodeError, UnicodeDecodeError):
        raw = {}
    ev = parse_event(event, raw if isinstance(raw, dict) else {}, tool)
    return format_reply(ev, _HANDLERS[event](ev))


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    tool = None
    if "--tool" in args:
        i = args.index("--tool")
        tool = args[i + 1]
        del args[i:i + 2]
    code, out, err = run_hook(args[0] if args else "", sys.stdin.buffer.read(), tool=tool)
    sys.stdout.write(out)
    sys.stderr.write(err)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
